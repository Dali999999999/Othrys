/// Standardized icon sizing scale for Othrys.
class AppIconSize {
  AppIconSize._();

  /// Badges, pills (10.0px).
  static const double xs = 10.0;

  /// Inline compact action buttons, prefixes (12.0px).
  static const double sm = 12.0;

  /// Standard action buttons, toolbar triggers (14.0px).
  static const double md = 14.0;

  /// Card lead icons, section headers (20.0px).
  static const double lg = 20.0;

  /// Illustrations, prominent status avatars (32.0px).
  static const double xl = 32.0;

  /// Empty states hero illustrations (48.0px).
  static const double hero = 48.0;
}
